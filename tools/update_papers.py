#!/usr/bin/env python3
"""Refresh _data/papers.yml from the arXiv API.

    python3 tools/update_papers.py

Edits you make by hand in _data/papers.yml are kept for papers already listed:
  role:  first | significant | collaboration   (controls which section a paper goes in)
  hide:  true                                  (drop a paper that isn't yours)
  venue / year / doi                           (fix journal details)
New papers get a role guessed from author position.
No dependencies beyond the standard library (writes YAML by hand).
"""
import json
import re
import time
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "_data" / "papers.yml"
QUERIES = ['au:"Matthew T. Miles"', 'au:"M. T. Miles"', 'au:"Matthew Miles"', "au:Miles_M_T",
           'au:Miles_M AND (abs:pulsar OR abs:"gravitational wave")']
# Author-name strings that are you. Anything else with "Miles" in it is someone else.
ME = re.compile(r"^(Matthew|Matt|M\.)\s*(T\.?\s*)?Miles$")
CATS = ("astro-ph", "gr-qc")
NS = {"a": "http://www.w3.org/2005/Atom", "x": "http://arxiv.org/schemas/atom"}
VENUES = {
    "10.1093/mnras": "MNRAS",
    "10.3847/2041-8213": "ApJL",
    "10.3847/1538-4357": "ApJ",
    "10.3847/1538-4365": "ApJS",
    "10.1017/pasa": "PASA",
    "10.1103/physrevd": "PRD",
    "10.1103/physrevlett": "PRL",
}


def fetch(query):
    url = "https://export.arxiv.org/api/query?" + urllib.parse.urlencode(
        {"search_query": query, "sortBy": "submittedDate", "sortOrder": "descending", "max_results": 300}
    )
    with urllib.request.urlopen(url, timeout=60) as r:
        return ET.fromstring(r.read())


def clean(title):
    t = " ".join(title.split())
    t = t.replace("$-$", "\u2212").replace("--", "\u2013")
    return re.sub(r"\$([^$]*)\$", r"\1", t)


def guess_role(pos, n):
    if pos == 1:
        return "first"
    if pos <= 3 or n <= 10 or pos <= 0.25 * n and n < 40:
        return "significant"
    return "collaboration"


def short_authors(authors, pos):
    me = "**M. T. Miles**"
    if pos == 1:
        return me + (" et al." if len(authors) > 1 else "")
    first = authors[0]
    if len(authors) <= 4:
        return ", ".join(me if i + 1 == pos else a for i, a in enumerate(authors))
    return f"{first} et al. (incl. {me}, author {pos} of {len(authors)})"


def load_existing():
    # papers.yml is written by this script as one JSON object per list item, which is valid YAML.
    if not OUT.exists():
        return {}
    out = {}
    for line in OUT.read_text().splitlines():
        if line.startswith("- {"):
            d = json.loads(line[2:])
            out[d["arxiv"]] = d
    return out


def main():
    existing = load_existing()
    papers = {}
    for q in QUERIES:
        root = fetch(q)
        for e in root.findall("a:entry", NS):
            cat = e.find("a:category", NS).get("term")
            if not cat.startswith(CATS):
                continue
            authors = [a.find("a:name", NS).text.strip() for a in e.findall("a:author", NS)]
            pos = next((i + 1 for i, a in enumerate(authors) if ME.match(a)), None)
            if pos is None:
                continue
            aid = re.sub(r"v\d+$", "", e.find("a:id", NS).text.rsplit("/abs/", 1)[-1])
            doi = e.find("x:doi", NS)
            doi = doi.text.strip() if doi is not None else ""
            venue = next((v for k, v in VENUES.items() if doi.lower().startswith(k)), "arXiv preprint" if not doi else "")
            papers[aid] = {
                "arxiv": aid,
                "title": clean(e.find("a:title", NS).text),
                "authors": short_authors(authors, pos),
                "n_authors": len(authors),
                "position": pos,
                "year": int(e.find("a:published", NS).text[:4]),
                "venue": venue,
                "doi": doi,
                "role": guess_role(pos, len(authors)),
            }
        time.sleep(3)  # arXiv asks for >= 3 s between requests

    for aid, old in existing.items():  # keep hand edits
        if aid in papers:
            for k in ("role", "hide", "venue", "year", "doi", "title"):
                if k in old:
                    papers[aid][k] = old[k]
        else:
            papers[aid] = old  # keep papers added by hand / no longer matched

    for p in papers.values():
        p["title"] = clean(p["title"])

    rows = sorted(papers.values(), key=lambda p: (p["year"], p["arxiv"]), reverse=True)
    header = "# Generated by tools/update_papers.py — hand edits to role/hide/venue/year/doi/title are preserved.\n"
    OUT.write_text(header + "".join("- " + json.dumps(p, ensure_ascii=False) + "\n" for p in rows))
    counts = {r: sum(p["role"] == r and not p.get("hide") for p in rows) for r in ("first", "significant", "collaboration")}
    print(f"wrote {len(rows)} papers to {OUT}  {counts}")


if __name__ == "__main__":
    main()
